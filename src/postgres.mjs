const SEED_SERVICES = [
  { id: 'goi-duong', name: 'Gội dưỡng thư giãn', duration: 45, price: 250000, description: 'Làm sạch dịu nhẹ, massage thư giãn và chăm sóc tóc cơ bản.', icon: 'sparkle' },
  { id: 'da-dau', name: 'Chăm sóc da đầu', duration: 60, price: 390000, description: 'Quy trình chăm sóc da đầu và thư giãn chuyên sâu.', icon: 'leaf' },
  { id: 'phuc-hoi', name: 'Phục hồi tóc', duration: 90, price: 650000, description: 'Chăm sóc và bổ sung dưỡng chất dành cho tóc cần phục hồi.', icon: 'flower' }
];

export async function openPostgresDatabase(connectionString) {
  const { Pool } = await import('pg');
  const pool = new Pool({
    connectionString,
    max: 4,
    connectionTimeoutMillis: 15000,
    idleTimeoutMillis: 30000,
    keepAlive: true
  });
  try {
    await pool.query(`CREATE TABLE IF NOT EXISTS services (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      duration INTEGER NOT NULL,
      price INTEGER NOT NULL,
      description TEXT NOT NULL,
      icon TEXT NOT NULL
    )`);
    await pool.query(`CREATE TABLE IF NOT EXISTS bookings (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      service_id TEXT NOT NULL REFERENCES services(id),
      customer_name TEXT NOT NULL,
      phone TEXT NOT NULL,
      booking_date TEXT NOT NULL,
      booking_time TEXT NOT NULL,
      note TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','completed','cancelled')),
      created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
    )`);
    await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS unique_active_slot ON bookings(booking_date, booking_time)
      WHERE status != 'cancelled'`);
    await pool.query('CREATE INDEX IF NOT EXISTS idx_bookings_date ON bookings(booking_date)');
    for (const item of SEED_SERVICES) {
      await pool.query(`INSERT INTO services (id,name,duration,price,description,icon)
        VALUES ($1,$2,$3,$4,$5,$6) ON CONFLICT (id) DO NOTHING`,
        [item.id, item.name, item.duration, item.price, item.description, item.icon]);
    }
    return { kind: 'postgres', pool, close: () => pool.end() };
  } catch (error) {
    await pool.end().catch(() => {});
    throw error;
  }
}
export async function listServicesPg(db) {
  const result = await db.pool.query('SELECT id,name,duration,price,description,icon FROM services ORDER BY price ASC');
  return result.rows;
}
export async function serviceExistsPg(db, id) {
  const result = await db.pool.query('SELECT 1 FROM services WHERE id=$1', [id]);
  return result.rowCount > 0;
}
export async function bookedSlotsPg(db, date) {
  const result = await db.pool.query("SELECT booking_time FROM bookings WHERE booking_date=$1 AND status!='cancelled'", [date]);
  return result.rows.map(row => row.booking_time);
}
export async function createBookingPg(db, data) {
  const result = await db.pool.query(`INSERT INTO bookings
    (service_id,customer_name,phone,booking_date,booking_time,note)
    VALUES ($1,$2,$3,$4,$5,$6) RETURNING id`,
    [data.serviceId, data.name, data.phone, data.date, data.time, data.note]);
  return Number(result.rows[0].id);
}
export async function listBookingsPg(db) {
  const result = await db.pool.query(`SELECT b.id,b.customer_name AS name,b.phone,b.booking_date AS date,
    b.booking_time AS time,b.note,b.status,b.created_at AS "createdAt",
    s.name AS "serviceName", s.price AS price
    FROM bookings b JOIN services s ON s.id=b.service_id
    ORDER BY b.booking_date DESC,b.booking_time DESC,b.id DESC`);
  return result.rows.map(row => ({ ...row, id: Number(row.id) }));
}
export async function getBookingPg(db, id) {
  const result = await db.pool.query('SELECT id,status,booking_date,booking_time FROM bookings WHERE id=$1', [id]);
  return result.rows[0] ?? null;
}
export async function changeBookingStatusPg(db, id, status, expectedStatus) {
  const result = await db.pool.query('UPDATE bookings SET status=$1 WHERE id=$2 AND status=$3 RETURNING id',
    [status, id, expectedStatus]);
  return result.rowCount > 0;
}
